def clean_text_b4(text):
    for src, tgt in GLOSSARY_REPLACEMENTS_B4:
        text = text.replace(src, tgt)
    for src, tgt in COMMON_S2T_B4.items():
        text = text.replace(src, tgt)
    return text

def parse_blocks(content):
    raw_blocks = re.split(r'\n\s*\n', content.strip())
    blocks = []
    for b in raw_blocks:
        b = b.strip()
        if not b:
            continue
        lines = b.split('\n')
        if len(lines) >= 3:
            try:
                idx = int(lines[0].strip())
                ts = lines[1].strip()
                txt = "\n".join(lines[2:])
                blocks.append((idx, ts, txt))
            except ValueError:
                continue
    return blocks

