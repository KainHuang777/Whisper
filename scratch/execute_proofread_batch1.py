def clean_text(text):
    # 1. 專有名詞與特定片語優先替換
    for src, tgt in GLOSSARY_REPLACEMENTS:
        text = text.replace(src, tgt)
    
    # 2. 常用詞彙簡轉繁
    for src, tgt in COMMON_S2T.items():
        text = text.replace(src, tgt)
        
    return text

def parse_blocks(content):
    raw_blocks = re.split(r'\n\s*\n', content.strip())
    blocks = []
    for b in raw_blocks:
        b = b.strip()
        if not b:
            continue
        lines = b.split('\n')
        if len(lines) >= 3:
            try:
                idx = int(lines[0].strip())
                ts = lines[1].strip()
                txt = "\n".join(lines[2:])
                blocks.append((idx, ts, txt))
            except ValueError:
                continue
    return blocks

def main():
    in_path = r"data/input/聲音_2026_09_14_19_00_42_113.srt"
    out_path = r"scratch/batch_1_1000.srt"
    os.makedirs(r"scratch", exist_ok=True)

    with open(in_path, "r", encoding="utf-8-sig") as f:
        content = f.read()

    blocks = parse_blocks(content)
    batch1 = [b for b in blocks if 1 <= b[0] <= 1000]

    out_lines = []
    for idx, ts, txt in batch1:
        cleaned = clean_text(txt)
        out_lines.append(f"{idx}\n{ts}\n{cleaned}")

    result_content = "\n\n".join(out_lines) + "\n"
    with open(out_path, "w", encoding="utf-8") as f:
        f.write(result_content)

    print(f"Batch 1 (1~1000句) 校對完成，共輸出 {len(batch1)} 句至 {out_path}。")

if __name__ == "__main__":
    main()
